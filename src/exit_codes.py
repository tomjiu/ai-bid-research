"""进程退出码规范（#601 R70）。

脚本自动化（smoke 脚本/CI/研究流水线）依赖**稳定可编程**的退出码。
本模块是唯一权威定义——main 各分支只引用这里的常量。

约定（**按实测行为锚定**——argparse 用法错误本身退 2，与
数据/环境错误历史同码，规范如实收录而非另造理想态）：

===  ==========================================================
码   语义
===  ==========================================================
0    成功（含「正常但无数据」与**容忍模式的坏文件降级**——
     失败已登记 failures/pending，非进程级错误）
1    无子命令（打印帮助后直落——main() 返回值）
2    用法错误（argparse 域：未知参数/缺必选）**与**
     数据/环境错误：源不存在、库不存在、--strict 下坏数据、
     路径过长（R44）、导出目标不可写、--retry 缺 API key
3    LLM 运行时失败：网络重试耗尽、输出不可解析
     （降级路径不占此码——park 进 pending 后整体仍 0）
===  ==========================================================

稳定性承诺：**只增不改**——已发布的码语义冻结；新码追加即可。
"""

from __future__ import annotations

#: 成功（含空数据集的正常路径）
EXIT_OK = 0
#: 用法错误（argparse 域）
EXIT_USAGE = 1
#: 数据/环境错误（源/目标/配置面）
EXIT_DATA = 2
#: LLM 运行时失败（网络/解析——非降级场景）
EXIT_LLM = 3

#: 人读说明（--help 尾注与文档共用）
EXIT_CODE_TABLE = (
    "退出码：0 成功（含空数据集/容忍降级）；1 无子命令（帮助面）；"
    "2 用法或数据/环境错误（源不存在/--strict 坏数据/路径不可写等）；"
    "3 LLM 运行时失败"
)


def describe_exit_code(code: int) -> str:
    """退出码的人读语义（测试与排障共用）。"""
    mapping = {
        EXIT_OK: "成功（含容忍降级）",
        EXIT_USAGE: "无子命令（帮助面）",
        EXIT_DATA: "用法或数据/环境错误",
        EXIT_LLM: "LLM 运行时失败",
    }
    return mapping.get(code, f"未定义退出码 {code}")
